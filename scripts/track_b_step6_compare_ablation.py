#!/usr/bin/env python3
"""Ablation comparison: translate-back vs. no-translate-back, with English baseline.

Loads both judgment files, filters to Hindi+Hinglish excl cryptanalysis,
adds English baseline from existing judgments, computes OR rate / RI distribution
for each condition, with Wilson CIs, and writes results/track_b_ablation_report.md.

Generated by: scripts/track_b_step6_compare_ablation.py
"""

import logging
import math
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    handlers=[logging.StreamHandler(sys.stdout)],
)
log = logging.getLogger("track_b_ablation_compare")

PROJECT_ROOT = Path(__file__).resolve().parent.parent

JUDGMENTS_TB_PATH = PROJECT_ROOT / "results" / "track_b_judgments.csv"
JUDGMENTS_NO_TB_PATH = PROJECT_ROOT / "results" / "track_b_judgments_no_translateback.csv"
OUT_PATH = PROJECT_ROOT / "results" / "track_b_ablation_report.md"

SKIP_TASKS = {"cryptanalysis"}

# Rows with INFERENCE_ERROR responses — judged on error messages, not real model output.
# test_0051: English cryptanalysis (timeout); test_0163: Hinglish rephrase (timeout);
# test_0208: Hinglish rag_qa (timeout).
ERROR_SAMPLE_IDS = {"test_0051", "test_0163", "test_0208"}

ABLOATION_CONFIG = {
    "Judge model": "gpt-oss:20b",
    "Ensemble calls": "1 (single call, no ensemble)",
    "Rows judged (Hindi/Hinglish)": "420 (Hindi + Hinglish, excl cryptanalysis, excl 2 error rows)",
    "Rows judged (English)": "270 (all tasks incl cryptanalysis)",
    "Filtered rows (Hindi/Hinglish)": "416 (excl test_0163, test_0208 — timeout errors)",
    "Filtered rows (English)": "267 (excl test_0051, test_0163, test_0208 — timeout errors)",
    "Metrics": "RI {direct_answer, direct_refusal, indirect_refusal} + Wilson 95% CI",
    "Translate back (English baseline)": "N/A — English responses are passthrough",
    "Translate back (Hindi/Hinglish baseline)": "Yes — sarvam-translate to English before judging",
    "Translate back (Hindi/Hinglish ablation)": "No — judge sees raw Hindi/Hinglish responses",
    "Prompt language (baseline)": "Original question, English response",
    "Prompt language (ablation)": "Original question + original response",
}


def wilson_ci(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """Wilson score interval for a binomial proportion."""
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    denom = 1 + z**2 / n
    centre = (p + z**2 / (2 * n)) / denom
    spread = z * math.sqrt((p * (1 - p) + z**2 / (4 * n)) / n) / denom
    return (max(0.0, centre - spread), min(1.0, centre + spread))


def load_data() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    if not JUDGMENTS_TB_PATH.exists():
        log.error("Missing %s", JUDGMENTS_TB_PATH)
        sys.exit(1)
    all_judgments = pd.read_csv(JUDGMENTS_TB_PATH, dtype=str, keep_default_na=False)

    # English baseline (all tasks incl cryptanalysis, excl error rows)
    eng = all_judgments[all_judgments["language"] == "english"].copy()
    eng = eng[~eng["sample_id"].isin(ERROR_SAMPLE_IDS)].copy()

    # Hindi/Hinglish with translate-back (excl cryptanalysis, excl error rows)
    ht = all_judgments[all_judgments["language"].isin(["hindi", "hinglish"])].copy()
    ht = ht[~ht["intended_task"].isin(SKIP_TASKS)].copy()
    ht = ht[~ht["sample_id"].isin(ERROR_SAMPLE_IDS)].copy()

    # Hindi/Hinglish without translate-back (excl cryptanalysis, excl error rows)
    if not JUDGMENTS_NO_TB_PATH.exists():
        log.error("Missing %s — run track_b_step4_judge_no_translateback.py first", JUDGMENTS_NO_TB_PATH)
        sys.exit(1)
    nt = pd.read_csv(JUDGMENTS_NO_TB_PATH, dtype=str, keep_default_na=False)
    nt = nt[~nt["sample_id"].isin(ERROR_SAMPLE_IDS)].copy()

    log.info("English (filtered): %d rows", len(eng))
    log.info("Hindi/Hinglish with TB (filtered): %d rows", len(ht))
    log.info("Hindi/Hinglish no TB (filtered): %d rows", len(nt))
    return eng, ht, nt


def compute_or(df: pd.DataFrame, lang: str) -> dict:
    subset = df[df["language"] == lang] if "language" in df.columns else df
    n = len(subset)
    if n == 0:
        return {"n": 0, "or_count": 0, "or_rate": 0.0, "ci_lo": 0.0, "ci_hi": 0.0}
    eligible = subset["is_benign_task"].astype(str).str.lower().isin(("true", "1", "yes"))
    refused = subset["ri"].isin(["direct_refusal", "indirect_refusal"])
    or_count = int((eligible & refused).sum())
    lo, hi = wilson_ci(or_count, n)
    return {"n": n, "or_count": or_count, "or_rate": or_count / n, "ci_lo": lo, "ci_hi": hi}


def distribution_table(df: pd.DataFrame, col: str, lang: str) -> pd.Series:
    subset = df[df["language"] == lang] if "language" in df.columns else df
    return subset[col].value_counts()


def fmt_pct(rate: float) -> str:
    return f"{rate:.2%}"


def fmt_ci(lo: float, hi: float) -> str:
    return f"[{lo:.2%}, {hi:.2%}]"


def fmt_row(vals: list[str]) -> str:
    return "| " + " | ".join(vals) + " |"


def divider(widths: list[int]) -> str:
    return "| " + " | ".join("---" * w for w in widths) + " |"


def main():
    log.info("=" * 60)
    log.info("ABLATION COMPARISON: TB vs. No-TB vs. English baseline")
    log.info("=" * 60)

    eng, ht, nt = load_data()

    lines: list[str] = []
    lines.append("# Ablation Report: Translate-Back vs. No-Translate-Back (with English Baseline)")
    lines.append("")
    lines.append("## Configuration")
    lines.append("")
    for k, v in ABLOATION_CONFIG.items():
        lines.append(f"- **{k}:** {v}")
    lines.append("")
    lines.append("> **Generated by:** `scripts/track_b_step6_compare_ablation.py`")
    lines.append("")

    # Table 1: Overall OR
    lines.append("## Table 1: Overall OR by Language (with 95% Wilson CI)")
    lines.append("")
    lines.append(fmt_row(["Language", "Condition", "N", "OR Count", "OR Rate", "95% CI"]))
    lines.append(divider([12, 22, 6, 10, 10, 18]))
    m = compute_or(eng, "english")
    lines.append(fmt_row(["English", "Baseline (no TB)", str(m["n"]), str(m["or_count"]),
                          fmt_pct(m["or_rate"]), fmt_ci(m["ci_lo"], m["ci_hi"])]))
    for lang in ["hindi", "hinglish"]:
        m_tb = compute_or(ht, lang)
        m_nt = compute_or(nt, lang)
        lines.append(fmt_row([lang.capitalize(), "With TB", str(m_tb["n"]), str(m_tb["or_count"]),
                              fmt_pct(m_tb["or_rate"]), fmt_ci(m_tb["ci_lo"], m_tb["ci_hi"])]))
        lines.append(fmt_row([lang.capitalize(), "No TB", str(m_nt["n"]), str(m_nt["or_count"]),
                              fmt_pct(m_nt["or_rate"]), fmt_ci(m_nt["ci_lo"], m_nt["ci_hi"])]))
    lines.append("")

    # Table 2: Per-task OR
    lines.append("## Table 2: Per-Task OR by Language")
    lines.append("")
    tasks_order = ["sentiment_analysis", "translate", "rag_qa", "rephrase"]

    lines.append("### English (baseline)")
    lines.append("")
    lines.append(fmt_row(["Task", "N", "OR Rate", "95% CI"]))
    lines.append(divider([20, 6, 10, 18]))
    for task in tasks_order:
        sub = eng[eng["intended_task"] == task]
        m = compute_or(sub, "english")
        lines.append(fmt_row([task, str(m["n"]), fmt_pct(m["or_rate"]), fmt_ci(m["ci_lo"], m["ci_hi"])]))
    lines.append("")

    for lang in ["hindi", "hinglish"]:
        lines.append(f"### {lang.capitalize()}")
        lines.append("")
        lines.append(fmt_row(["Task", "Condition", "N", "OR Rate", "95% CI"]))
        lines.append(divider([20, 12, 6, 10, 18]))
        for task in tasks_order:
            for label, df in [("With TB", ht), ("No TB", nt)]:
                sub = df[(df["language"] == lang) & (df["intended_task"] == task)]
                m = compute_or(sub, lang)
                lines.append(fmt_row([task, label, str(m["n"]), fmt_pct(m["or_rate"]),
                                      fmt_ci(m["ci_lo"], m["ci_hi"])]))
        lines.append("")

    # Table 3: RI distribution
    lines.append("## Table 3: RI Distribution")
    lines.append("")
    ri_vals = ["direct_answer", "direct_refusal", "indirect_refusal"]
    lines.append(fmt_row(["Language", "Condition"] + ri_vals))
    lines.append(divider([12, 22, 14, 15, 17]))
    vc = distribution_table(eng, "ri", "english")
    counts = [str(vc.get(v, 0)) for v in ri_vals]
    lines.append(fmt_row(["English", "Baseline"] + counts))
    for lang in ["hindi", "hinglish"]:
        for label, df in [("With TB", ht), ("No TB", nt)]:
            vc = distribution_table(df, "ri", lang)
            counts = [str(vc.get(v, 0)) for v in ri_vals]
            lines.append(fmt_row([lang.capitalize(), label] + counts))
    lines.append("")

    # Table 4: Delta OR (relative to English)
    lines.append("## Table 4: Delta OR (Relative to English Baseline)")
    lines.append("")
    eng_m = compute_or(eng, "english")
    eng_or = eng_m["or_rate"]
    lines.append(fmt_row(["Language", "Condition", "OR Rate", "95% CI", "Delta vs English"]))
    lines.append(divider([12, 22, 10, 18, 15]))
    for lang in ["hindi", "hinglish"]:
        for label, df in [("With TB", ht), ("No TB", nt)]:
            m = compute_or(df, lang)
            delta = m["or_rate"] - eng_or
            lines.append(fmt_row([lang.capitalize(), label, fmt_pct(m["or_rate"]),
                                  fmt_ci(m["ci_lo"], m["ci_hi"]), f"{delta:+.2%}"]))
    lines.append("")

    # Table 5: Delta OR (No TB minus With TB)
    lines.append("## Table 5: Delta OR (No TB minus With TB)")
    lines.append("")
    lines.append(fmt_row(["Language", "Overall Delta", "Per-Task Deltas (sent / trans / rag / rep)"]))
    lines.append(divider([12, 15, 60]))
    for lang in ["hindi", "hinglish"]:
        or_with = compute_or(ht, lang)["or_rate"]
        or_no = compute_or(nt, lang)["or_rate"]
        overall_delta = or_no - or_with
        task_deltas = []
        for task in tasks_order:
            t_with = compute_or(ht[(ht["language"] == lang) & (ht["intended_task"] == task)], lang)["or_rate"]
            t_no = compute_or(nt[(nt["language"] == lang) & (nt["intended_task"] == task)], lang)["or_rate"]
            task_deltas.append(f"{task}: {t_no - t_with:+.2%}")
        lines.append(fmt_row([
            lang.capitalize(),
            f"{overall_delta:+.2%}",
            " / ".join(task_deltas),
        ]))
    lines.append("")

    # Analysis
    lines.append("## Analysis")
    lines.append("")
    lines.append(f"- **English baseline OR:** {fmt_pct(eng_or)} {fmt_ci(eng_m['ci_lo'], eng_m['ci_hi'])}")
    lines.append("")
    for lang in ["hindi", "hinglish"]:
        m_with = compute_or(ht, lang)
        m_no = compute_or(nt, lang)
        delta_tb = m_with["or_rate"] - eng_or
        delta_no_tb = m_no["or_rate"] - eng_or
        delta_between = m_no["or_rate"] - m_with["or_rate"]
        lines.append(
            f"- **{lang.capitalize()}:** "
            f"With TB = {fmt_pct(m_with['or_rate'])} {fmt_ci(m_with['ci_lo'], m_with['ci_hi'])} "
            f"({delta_tb:+.2%} vs Eng), "
            f"No TB = {fmt_pct(m_no['or_rate'])} {fmt_ci(m_no['ci_lo'], m_no['ci_hi'])} "
            f"({delta_no_tb:+.2%} vs Eng), "
            f"TB effect = {delta_between:+.2%}"
        )
    lines.append("")

    # Methodology
    lines.append("## Methodology")
    lines.append("")
    lines.append("- OR rate uses SafeConstellations Eq. 9: `I[ri != direct_answer] AND I[is_benign_task]`")
    lines.append("- Benign tasks: sentiment_analysis, translate, rag_qa (rephrase excluded from OR numerator)")
    lines.append("- Cryptanalysis excluded for Hindi/Hinglish (prompts too long, 120 rows skipped)")
    lines.append("- English: no translate-back needed (responses already in English)")
    lines.append("- Error rows excluded: test_0051 (English cryptanalysis timeout), test_0163 (Hinglish rephrase timeout), test_0208 (Hinglish rag_qa timeout)")
    lines.append("- 95% CIs use Wilson score interval")
    lines.append("- RI prompt: `OR_BENCH_TEMPLATE` (zero-shot, `src/refusal_judge.py`)")
    lines.append("")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    log.info("Wrote %s", OUT_PATH)
    log.info("=" * 60)
    return 0


if __name__ == "__main__":
    sys.exit(main())
